const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('cueDesktop',{
  apiConsole:provider=>ipcRenderer.invoke('cue:api-console',provider),
  apiStatus:()=>ipcRenderer.invoke('cue:api-status'),
  apiConnect:data=>ipcRenderer.invoke('cue:api-connect',data),
  apiCancelConnect:provider=>ipcRenderer.invoke('cue:api-cancel-connect',provider),
  apiDisconnect:provider=>ipcRenderer.invoke('cue:api-disconnect',provider),
  apiModels:provider=>ipcRenderer.invoke('cue:api-models',provider),
  apiAnswer:data=>ipcRenderer.invoke('cue:api-answer',data),
  apiInterrupt:id=>ipcRenderer.invoke('cue:api-interrupt',id),
  onApiAnswer:callback=>{const fn=(_e,event)=>callback(event);ipcRenderer.on('cue:api-answer-event',fn);return ()=>ipcRenderer.removeListener('cue:api-answer-event',fn);},
  deviceInfo:()=>ipcRenderer.invoke('cue:device-info'),
  accountStatus:()=>ipcRenderer.invoke('cue:account-status'),
  accountSignIn:options=>ipcRenderer.invoke('cue:account-signin',options),
  accountCancel:()=>ipcRenderer.invoke('cue:account-cancel'),
  accountModels:()=>ipcRenderer.invoke('cue:account-models'),
  accountSelect:id=>ipcRenderer.invoke('cue:account-select',id),
  accountDisconnect:()=>ipcRenderer.invoke('cue:account-disconnect'),
  accountUsage:()=>ipcRenderer.invoke('cue:account-usage'),
  accountAnswer:data=>ipcRenderer.invoke('cue:account-answer',data),
  accountInterrupt:id=>ipcRenderer.invoke('cue:account-interrupt',id),
  onAccountState:callback=>{const fn=(_e,state)=>callback(state);ipcRenderer.on('cue:account-state',fn);return ()=>ipcRenderer.removeListener('cue:account-state',fn);},
  onAccountAnswer:callback=>{const fn=(_e,event)=>callback(event);ipcRenderer.on('cue:account-answer-event',fn);return ()=>ipcRenderer.removeListener('cue:account-answer-event',fn);},
  ready:()=>ipcRenderer.send('cue:ready'),
  reportPhase:phase=>ipcRenderer.send('cue:phase',phase),
  setPinned:value=>ipcRenderer.send('cue:pin',Boolean(value)),
  close:()=>ipcRenderer.send('cue:close'),
  status:()=>ipcRenderer.invoke('cue:status'),
  openKnowledge:(kind,interviewId)=>ipcRenderer.invoke('cue:knowledge-open',kind,interviewId),
  reloadKnowledge:()=>ipcRenderer.invoke('cue:knowledge-reload'),
  requestMicrophone:()=>ipcRenderer.invoke('cue:microphone'),
  protectCapture:value=>ipcRenderer.invoke('cue:protection',Boolean(value)),
  startShareView:()=>ipcRenderer.invoke('cue:share-start'),
  stopShareView:()=>ipcRenderer.invoke('cue:share-stop'),
  onShareState:callback=>{if(typeof callback==='function')ipcRenderer.on('cue:share-state',(_event,state)=>callback(state));},
  onAction:callback=>{if(typeof callback==='function')ipcRenderer.on('cue:action',(_event,action)=>callback(action));},
});
